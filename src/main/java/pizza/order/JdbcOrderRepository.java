package pizza.order;

import org.springframework.jdbc.core.RowMapper;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.stereotype.Repository;
import pizza.customer.Address;
import pizza.customer.Customer;

import javax.sql.DataSource;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.LocalDateTime;
import java.util.List;

/**
 * Uses the {@link JdbcClient} (since Spring 6.1) -- a fluent alternative to the {@code JdbcTemplate}
 * with named parameters. The id of a new order is generated by the database.
 */
@Repository
public class JdbcOrderRepository implements OrderRepository {

    public static final String INSERT_SQL = """
            INSERT INTO orders (customer_id, total_price, eta)
            VALUES (:customerId, :totalPrice, :eta)""";
    public static final String SELECT_ALL_SQL = """
            SELECT o.id, o.total_price, o.eta,
                   c.id AS customer_id, c.full_name, c.phone_number, c.street, c.postal_code, c.city
            FROM orders o
            JOIN customers c ON c.id = o.customer_id
            ORDER BY o.id""";

    private final JdbcClient jdbcClient;
    private final RowMapper<Order> rowMapper;

    public JdbcOrderRepository(DataSource dataSource) {
        this.jdbcClient = JdbcClient.create(dataSource);
        this.rowMapper = new OrderRowMapper();
    }

    @Override
    public Order save(Order order) {
        KeyHolder keyHolder = new GeneratedKeyHolder();
        this.jdbcClient.sql(INSERT_SQL)
                .param("customerId", order.getCustomer().getId())
                .param("totalPrice", order.getTotalPrice())
                .param("eta", order.getEstimatedTimeOfDelivery())
                .update(keyHolder, "id");
        order.setId(keyHolder.getKeyAs(Long.class));
        return order;
    }

    @Override
    public List<Order> findAll() {
        return this.jdbcClient.sql(SELECT_ALL_SQL)
                .query(this.rowMapper)
                .list();
    }

    //
    // --- inner classes ---
    //

    static class OrderRowMapper implements RowMapper<Order> {
        @Override
        public Order mapRow(ResultSet rs, int rowNum) throws SQLException {
            Customer customer = new Customer(
                    rs.getLong("customer_id"),
                    rs.getString("full_name"),
                    new Address(
                            rs.getString("street"),
                            rs.getString("postal_code"),
                            rs.getString("city")
                    ),
                    rs.getString("phone_number")
            );
            return new Order(
                    rs.getLong("id"),
                    customer,
                    rs.getBigDecimal("total_price"),
                    rs.getObject("eta", LocalDateTime.class)
            );
        }
    }
}
